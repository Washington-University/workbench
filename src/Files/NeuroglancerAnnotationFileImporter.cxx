/**
 * Convert a dimension to a string representation
 * @param dimension
 *    The dimension
 * @return
 *    String describing dimension
 */
AString
NeuroglancerAnnotationFileImporter::dimensionToString(const Dimension& dimension)
{
    AString axisText;
    switch (dimension.m_axis) {
        case Axis::X:
            axisText = "X";
            break;
        case Axis::Y:
            axisText = "Y";
            break;
        case Axis::Z:
            axisText = "Z";
            break;
    }
    
    AString unitText;
    switch (dimension.m_units) {
        case Unit::MILLIMETERS:
            unitText = "Millimeters";
            break;
        case Unit::SECONDS:
            unitText = "Seconds";
            break;
        case Unit::UNITLESS:
            unitText = "Unitless";
            break;
    }
    AString s("Axis=" + axisText
              + ", Unit=" + unitText
              + ", UnitScale=" + AString::number(dimension.m_unitScale)
              + ", Resolution=" + AString::number(dimension.m_resolution));
    
    return s;
}

/**
 * Convert an annotation type to a string representation
 * @param annotationType
 *    The annotation type
 * @return
 *    String describing data type
 */
AString
NeuroglancerAnnotationFileImporter::annotationFileTypeToString(const AnnotationFileType& annotationFileType)
{
    AString annTypeName("Invalid");
    switch (annotationFileType) {
        case AnnotationFileType::AXIS_ALIGNED_BOUNDING_BOX:
            annTypeName = "Axis Aligned Bounding Box";
            break;
        case AnnotationFileType::ELLIPSOID:
            annTypeName = "Ellipsoid";
            break;
        case AnnotationFileType::LINE:
            annTypeName = "Line";
            break;
        case AnnotationFileType::POINT:
            annTypeName = "Point";
            break;
        case AnnotationFileType::POLYLINE:
            annTypeName = "Polyline";
            break;
    }
    return annTypeName;
}

/**
 * Read the data files in the 'byId" directory
 * Each file in the directory contains data for one annotation.
 */
void
NeuroglancerAnnotationFileImporter::readNeuroglancerAnnotationFiles()
{
    QDir dir(m_byIdDirectoryName);
    if ( ! dir.exists()) {
        throw DataFileException("byID directory does not exist: "
                                + m_byIdDirectoryName);
    }
    
    const QStringList filenamesList(dir.entryList(QDir::Files));
    QStringListIterator iter(filenamesList);
    std::vector<AString> annFileNames(filenamesList.begin(),
                                      filenamesList.end());
    AStringNaturalComparison::sortStringVector(annFileNames);
    
    float xScale(1.0);
    float yScale(1.0);
    float zScale(1.0);
    if (m_xDimension.m_valid) {
        xScale = m_xDimension.m_unitScale * m_xDimension.m_resolution;
        CaretAssert(xScale != 0.0);
    }
    if (m_yDimension.m_valid) {
        yScale = m_yDimension.m_unitScale * m_yDimension.m_resolution;
        CaretAssert(yScale != 0.0);
    }
    if (m_zDimension.m_valid) {
        zScale = m_zDimension.m_unitScale * m_zDimension.m_resolution;
        CaretAssert(zScale != 0.0);
    }

    for (const AString& filenameOnly : annFileNames) {
        const AString pathAndName(m_byIdDirectoryName
                                  + QDir::separator()
                                  + filenameOnly);
        QFile file(pathAndName);
        if ( ! file.open(QFile::ReadOnly)) {
            throw DataFileException("Failed to read file "
                                    + pathAndName);
        }
        
        bool validFlag(false);
        const uint64_t filenameInt(filenameOnly.toULong(&validFlag));
        if ( ! validFlag) {
            CaretLogSevere("Failed to convert "
                           + filenameOnly
                           + " to an unsigned long");
        }
        
        /*
         * Use a datastream to read the file
         */
        QDataStream dataStream(&file);
        
        QByteArray emptyByteArray;
        /* probably want readRelationshipDataAfterAnnotationFlag to be true */
        const bool readRelationshipDataAfterAnnotationFlag(false);
        NewAnnoationInformation nfi(readAnnotationFromDataStream(&file,
                                                                 emptyByteArray,
                                                                 dataStream,
                                                                 FeatureItemGroup::getDefaultGroupID(),
                                                                 filenameInt,
                                                                 readRelationshipDataAfterAnnotationFlag));
        /*
         * DO NOT reference nfi.m_featureAndPropertiesList
         * after calling addFeature as it is destroyed if
         * not added to model.
         */
        m_featureFile->addFeature(nfi.m_featureAndPropertiesList);
    }
}

/**
 * Read an annontation from a datastream
 * @param file
 *    File containing annotation.  If NULL, annotation is being read from in-memory data
 * @param dataBytes
 *    If 'file' is NULL, the annotation is being read from this byte array
 * @param dataStream
 *   The datastream
 * @param relationshipID
 *    The relationship that groups this annotation with other annotations
 * @param annotationID
 *    The annotation ID (may be filename when each annotation in its own file)
 * @param readRelationshipDataAfterAnnotationFlag
 *    If true, read relationship data that is after the annotation
 * @return
 *    Name and data for adding to a model
 */
NeuroglancerAnnotationFileImporter::NewAnnoationInformation
NeuroglancerAnnotationFileImporter::readAnnotationFromDataStream(QFile* file,
                                                                 const QByteArray& dataBytes,
                                                                 QDataStream& dataStream,
                                                                 const uint64_t relationshipID,
                                                                 const uint64_t annotationID,
                                                                 const bool readRelationshipDataAfterAnnotationFlag)
{
    /*
     * Position/radii vectors, required by the annotation type, encoded as
     * float32le values:
     *
     *   - POINT:
     *       The position vector.
     *
     *   - LINE:
     *       The first endpoint position, followed by the second endpoint
     *       position.
     *
     *   - AXIS_ALIGNED_BOUNDING_BOX:
     *       The first position, followed by the second position.
     *
     *   - ELLIPSOID:
     *       The center position, followed by the radii vector.
     *
     *   - POLYLINE:
     *       The number of points as a uint32le value, followed by the
     *       position of each point as float32le.
     *
     * Properties, encoded per their type:
     *
     *   - uint32, int32, float32:
     *       Encoded as a little-endian value.
     *
     *   - uint16, int16:
     *       Encoded as a little-endian value.
     *
     *   - uint8, int8, rgb, rgba:
     *       Encoded as-is (no byte-order conversion needed).
     *
     * Padding:
     *   Up to 3 padding bytes (value 0) to align the next field to a
     *   4-byte offset.
     *
     * Below is ONLY when each annotation is in a single file (NOT sharded)
     *
     * Relationships, for each relationship specified in the info JSON file:
     *
     *   1. The number of object IDs, as a uint32le value.
     *   2. Each related object ID, as a uint64le value.
     */
    dataStream.setByteOrder(QDataStream::LittleEndian);
    dataStream.setFloatingPointPrecision(QDataStream::SinglePrecision);
    
    /*
     * The property values are added into same row as the annotation in the model
     */
    QList<QStandardItem*> modelRowPropertyValues;
    
    /*
     * The property values are also added to the annotation
     */
    std::vector<const FeaturePropertyValue*> neuroglancerAnnotationPropertyValues;
    
    float annotationSize(2.0);
    QColor annotationColor(255, 255, 255, 255);
    
    /*
     * We need to track the number of bytes read.  In sharded files,
     * there may be multiple annotations and each new annotation is
     * on a 4-byte boundary.  Thus we may need to skip 1 to 3 bytes
     * after reading an annotation.
     *
     * When reading sharded data, data is read from a QByteArray that
     * is in memory.  A QDataStream reads from the the byte array.
     * Unlike QFile, QDataStream does not provide a "position" function.
     */
    int64_t numberOfBytesRead(0);
    
    float i, j, k;
    dataStream >> i >> j >> k;
    numberOfBytesRead += (sizeof(float) * 3);
    
    const int32_t numProperties(m_properties.size());
    for (int32_t iProp = 0; iProp < numProperties; iProp++) {
        CaretAssertVectorIndex(m_properties, iProp);
        const NeuroglancerProperty& property(m_properties[iProp]);
        
        const int64_t offset(property.m_fileOffset);
        CaretAssert(offset > 0);
        
        FeaturePropertyDataTypeEnum::Enum propertyType(FeaturePropertyDataTypeEnum::INVALID);
        QVariant propertyValue = "InvalidSeekFailed";
        AString propertyLabelText;
            switch (property.m_propertyType) {
                case NeuroglancerDataType::INVALID:
                    propertyType = FeaturePropertyDataTypeEnum::INVALID;
                    propertyValue = "InvalidDataType";
                    break;
                case NeuroglancerDataType::RGB:
                {
                    uint8_t r, g, b;
                    dataStream >> r >> g >> b;
                    QColor color(r, g, b);
                    propertyValue = QVariant::fromValue(color);
                    propertyType = FeaturePropertyDataTypeEnum::RGBA;
                    
                    annotationColor.setRgb(r, g, b);
                    numberOfBytesRead += (sizeof(uint8_t) * 3);
                }
                    break;
                case NeuroglancerDataType::RGBA:
                {
                    uint8_t r, g, b, a;
                    dataStream >> r >> g >> b >> a;
                    QColor color(r, g, b, a);
                    propertyValue = QVariant::fromValue(color);
                    propertyType = FeaturePropertyDataTypeEnum::RGBA;
                    
                    annotationColor.setRgb(r, g, b, a);
                    numberOfBytesRead += (sizeof(uint8_t) * 4);
                }
                    break;
                case NeuroglancerDataType::UINT8:
                {
                    uint8_t v;
                    dataStream >> v;
                    propertyValue = static_cast<uint32_t>(v);
                    propertyType = FeaturePropertyDataTypeEnum::UNSIGNED_INTEGER;
                    numberOfBytesRead += (sizeof(uint8_t) * 1);
                }
                    break;
                case NeuroglancerDataType::INT8:
                {
                    int8_t v;
                    dataStream >> v;
                    propertyValue = static_cast<int32_t>(v);
                    propertyType = FeaturePropertyDataTypeEnum::INTEGER;
                    numberOfBytesRead += (sizeof(int8_t) * 1);
                }
                    break;
                case NeuroglancerDataType::UINT16:
                {
                    uint16_t v;
                    dataStream >> v;
                    propertyValue = static_cast<uint32_t>(v);
                    propertyType = FeaturePropertyDataTypeEnum::UNSIGNED_INTEGER;
                    numberOfBytesRead += (sizeof(uint16_t) * 1);
                }
                    break;
                case NeuroglancerDataType::INT16:
                {
                    int16_t v;
                    dataStream >> v;
                    propertyValue = static_cast<int32_t>(v);
                    propertyType = FeaturePropertyDataTypeEnum::INTEGER;
                    numberOfBytesRead += (sizeof(int16_t) * 1);
                }
                    break;
                case NeuroglancerDataType::UINT32:
                {
                    uint32_t v;
                    dataStream >> v;
                    propertyValue = v;
                    propertyType = FeaturePropertyDataTypeEnum::UNSIGNED_INTEGER;
                    numberOfBytesRead += (sizeof(uint32_t) * 1);
                }
                    break;
                case NeuroglancerDataType::INT32:
                {
                    int32_t v;
                    dataStream >> v;
                    propertyValue = v;
                    propertyType = FeaturePropertyDataTypeEnum::INTEGER;
                    numberOfBytesRead += (sizeof(int32_t) * 1);
                }
                    break;
                case NeuroglancerDataType::FLOAT32:
                {
                    float v;
                    dataStream >> v;
                    propertyValue = v;
                    propertyType = FeaturePropertyDataTypeEnum::FLOAT;
                    numberOfBytesRead += (sizeof(float) * 1);
                }
                    break;
            }
            
            if (property.m_enumValueLabel.empty()) {
                if (property.m_description == "size") {
                    annotationSize = propertyValue.toFloat();
                }
            }
            else {
                int32_t labelIndex(-1);
                switch (propertyType) {
                    case FeaturePropertyDataTypeEnum::INVALID:
                        break;
                    case FeaturePropertyDataTypeEnum::RGBA:
                        break;
                    case FeaturePropertyDataTypeEnum::UNSIGNED_INTEGER:
                        labelIndex = static_cast<int32_t>(propertyValue.toUInt());
                        break;
                    case FeaturePropertyDataTypeEnum::INTEGER:
                        labelIndex = propertyValue.toInt();
                        break;
                    case FeaturePropertyDataTypeEnum::FLOAT:
                        break;
                    case FeaturePropertyDataTypeEnum::LABEL:
                        break;
                }
                
                if (labelIndex >= 0) {
                    auto labelIter(property.m_enumValueLabel.find(labelIndex));
                    if (labelIter != property.m_enumValueLabel.end()) {
                        propertyLabelText = labelIter->second;
                        propertyType = FeaturePropertyDataTypeEnum::LABEL;
                    }
                }
            }
        
        FeaturePropertyValue* fpv(new FeaturePropertyValue(property.m_description,
                                                           propertyType,
                                                           propertyValue,
                                                           propertyLabelText,
                                                           property.m_labelModel));
        modelRowPropertyValues.push_back(fpv);
        neuroglancerAnnotationPropertyValues.push_back(fpv);
    }

    QByteArray extraBytes;
    if (file != NULL) {
        CaretAssert(numberOfBytesRead == file->pos());
        
        /*
         * After reading the annotation, the file position must be at
         * a 4-byte offset (see comment at beginning of this function).
         */
        const int64_t bytesToSkip(file->pos() % 4);
        CaretAssert((bytesToSkip >= 0)
                    && (bytesToSkip <= 3));
        /*
         * QFile::skip() was added in Qt 5.10.0
         */
        const int64_t bytesActuallySkipped(QtFileHelper::safeSkip(file, bytesToSkip));
        if (bytesToSkip != bytesActuallySkipped) {
            CaretLogWarning("Failed to skip bytes at end of reading Neuroglancer Annotation");
        }
        
        if (m_debugFlag) {
            const int64_t bytesLeft(file->size() - file->pos());
            if (bytesLeft > 0) {
                /*
                 * Read the remaining bytes
                 */
                extraBytes.resize(bytesLeft);
                dataStream.readRawData(extraBytes.data(), bytesLeft);
            }
        }
    }
    else {
        const int64_t bytesToSkip(numberOfBytesRead % 4);
        for (int64_t i = 0; i < bytesToSkip; i++) {
            if (dataStream.atEnd()) {
                break;
            }
            uint8_t bt;
            dataStream >> bt;
        }
//        /*
//         * Read any remaining bytes
//         */
//        extraBytes.reserve(256);
//        while (  ! dataStream.atEnd()) {
//            uint8_t bt;
//            dataStream >> bt;
//            extraBytes.push_back(bt);
//        }
//        
//        /*
//         * There is no "pos()" in QDataStream so we need to determine
//         * if we are at a 4-byte boundary and if there is "padding"
//         */
//        const int64_t dataArrayPos(dataBytes.length() - extraBytes.length());
//        const int64_t remainder(dataArrayPos % 4);
//        
//        if (remainder >= 0) {
//            /*
//             * Skip over the padded bytes
//             */
//            if (remainder <= extraBytes.size()) {
//                extraBytes = extraBytes.mid(remainder);
//            }
//            else {
//                extraBytes.clear();
//            }
//        }
    }
    
    if ( ! extraBytes.isEmpty()) {
        std::cout << "Annotation: " << getFileName() << " has extra bytes at end, num="
        << extraBytes.size() << " mod 4=" << (extraBytes.size() % 4) << std::endl;
    }
    
    if (readRelationshipDataAfterAnnotationFlag) {
        if ( ! m_relationships.empty()) {
            if (extraBytes.size() >= 4) {
                /*
                 * For each relationship specified by the info JSON file:
                 *   The number of object ids as a uint32le value.
                 *   Each related object id, as a uint64le value.
                 */
                QDataStream relStream(extraBytes);
                relStream.setByteOrder(QDataStream::LittleEndian);
                relStream.setFloatingPointPrecision(QDataStream::SinglePrecision);
                
                uint32_t numberOfObjectIDs;
                relStream >> numberOfObjectIDs;
                std::cout << "Annotation ID=" << annotationID << " has count relationship IDs="
                << numberOfObjectIDs << std::endl;
                
                for (uint32_t i = 0; i < numberOfObjectIDs; i++) {
                    quint64 id; /* cannot use uint64_t on Linux */
                    relStream >> id;
                    std::cout << " " << id;
                }
                std::cout << std::endl;
            }
        }
    }
    
    bool supportedFlag(false);
    switch (m_annotationType) {
        case FeatureItemTypeEnum::INVALID:
            break;
        case FeatureItemTypeEnum::POINT:
            supportedFlag = true;
            break;
    }
    if ( ! supportedFlag) {
        throw DataFileException("Neuroglancer Annotation type not supported for "
                                + FeatureItemTypeEnum::toGuiName(m_annotationType));
    }
    
    std::vector<Vector3D> ijks { Vector3D(i, j, k) };
    
    /*
     * Create the annotation
     */
    FeatureItem* na = new FeatureItem(m_annotationType,
                                      relationshipID,
                                      annotationID,
                                      ijks,
                                      annotationColor,
                                      annotationSize,
                                      neuroglancerAnnotationPropertyValues);

    /*
     * The annotation and properties must be inserted
     * as a row.  There does not appear to be a way
     * to add columns to a stadard item and keep them
     * in the same row.
     */
    QList<QStandardItem*> newRow;
    newRow.push_back(na);
    newRow.append(modelRowPropertyValues);
    
    NewAnnoationInformation nfi(annotationID,
                              newRow);
    return nfi;
}


/**
 * Read the sharded data files for the given sharding data type
 * Sharded files contain one or more annotations in a single file.
 * @param shardingInfo
 *    The sharding info
 * @param shardingDataType
 *    Type of data stored in sharding
 * @param shardingDataDirectoryName
 *    Name of directory containing the sharded data
 */
void
NeuroglancerAnnotationFileImporter::readNeuroglancerAnnotationShardedFiles(const Sharding& shardingInfo,
                                                                    const ShardingDataType shardingDataType,
                                                                    const AString& shardingDataDirectoryName)
{
    QDir dir(shardingDataDirectoryName);
    if ( ! dir.exists()) {
        throw DataFileException("Read sharding directory does not exist: "
                                + shardingDataDirectoryName);
    }
    
    /*
     * For each shard number in the range [0, 2**shard_bits), there is a
     * <shard>.shard file, where <shard> is the lowercase base-16 shard number
     * zero padded to ceil(shard_bits/4) digits.
     */
    const int32_t numShardFiles(std::exp2(shardingInfo.m_shardBits));
    if (m_debugFlag) std::cout << "Num shard files: " << numShardFiles << std::endl;
    const int32_t numDigitsInFileName(std::ceil(shardingInfo.m_shardBits / 4));
    if (m_debugFlag)std::cout << "   Num digits in filename: " << numDigitsInFileName << std::endl;

    std::vector<AString> allShardFileNames;
    for (int32_t iFile = 0; iFile < numShardFiles; iFile++) {
        /*
         * Create filename from number with zero padding at beginning of filename
         * Filenames are in form "#.shard" where "#" is one or more digits
         * with leading zeros.
         */
        const AString filenameNumber(AString::number(iFile).rightJustified(numDigitsInFileName, '0'));
        const AString filenameOnly(filenameNumber + ".shard");
        const AString pathAndName(shardingDataDirectoryName
                                  + QDir::separator()
                                  + filenameOnly);
        allShardFileNames.push_back(pathAndName);
    }
    
    AStringNaturalComparison::sortStringVector(allShardFileNames);
    if (m_debugFlag)std::cout << "Sorted shard filenames" << std::endl;
    for (const AString& name : allShardFileNames) {
        if (m_debugFlag)std::cout << "   " << name << std::endl;
    }
    
    float xScale(1.0);
    float yScale(1.0);
    float zScale(1.0);
    if (m_xDimension.m_valid) {
        xScale = m_xDimension.m_unitScale * m_xDimension.m_resolution;
        CaretAssert(xScale != 0.0);
    }
    if (m_yDimension.m_valid) {
        yScale = m_yDimension.m_unitScale * m_yDimension.m_resolution;
        CaretAssert(yScale != 0.0);
    }
    if (m_zDimension.m_valid) {
        zScale = m_zDimension.m_unitScale * m_zDimension.m_resolution;
        CaretAssert(zScale != 0.0);
    }
    
    for (const AString& shardFileName : allShardFileNames) {
        if (m_debugFlag) std::cout << "Processing shareded annotations file: " << shardFileName << std::endl;
        
        QFile file(shardFileName);
        if ( ! file.open(QFile::ReadOnly)) {
            throw DataFileException("Failed to read file "
                                    + shardFileName);
        }
        if (m_debugFlag) std::cout << "File length: " << file.size() << std::endl;
        
        /*
         * Neuorglancer files are LITTLE ENDIAN Single Precision
         */
        QDataStream dataStream(&file);
        dataStream.setByteOrder(QDataStream::LittleEndian);
        dataStream.setFloatingPointPrecision(QDataStream::SinglePrecision);
        
        /*
         * From https://github.com/google/neuroglancer/blob/master/src/datasource/precomputed/sharded.md
         *
         * The first 2**minishard_bits * 16 bytes of each shard file is the
         * "shard index" consisting of 2**minishard_bits entries of the form:
         * - start_offset: uint64le, specifies the inclusive start byte offset
         *   of the "minishard index" in the shard file.
         * - end_offset: uint64le, specifies the exclusive end byte offset of the
         *   "minishard index" in the shard file.
         * Both the start_offset and end_offset are relative to the end of the
         * "shard index", i.e. shard_index_end = 2**minishard_bits * 16 bytes.
         *
         * That is, the encoded "minishard index" for a given minishard is stored
         * in the byte range [shard_index_end + start_offset, shard_index_end + end_offset)
         * of the shard file. A zero-length byte range indicates that there are no
         * chunk IDs in the minishard.
         */
        if (m_debugFlag) std::cout << "2**4: " << std::exp2(4.0) << std::endl;
        if (m_debugFlag) shardingInfo.print("By ID Sharding");
        const int64_t numEntries(std::exp2(shardingInfo.m_minishardBits));
        const int64_t shardIndexLength(numEntries * 16);
        const int64_t shardIndexEnd(shardIndexLength);
        if (m_debugFlag) std::cout << "   Num Entries: " << numEntries << std::endl;
        if (m_debugFlag) std::cout << "   Shard Index Length: " << shardIndexLength << std::endl;
        
        /*
         * Read the start and end offsets of the shards
         */
        std::vector<std::pair<uint64_t, uint64_t>> minishardStartOffsetAndLength;
        for (int64_t i = 0; i < numEntries; i++) {
            quint64 startOffset, endOffset; /* cannot use uint64_t on Linux */
            dataStream >> startOffset >> endOffset;
            startOffset += shardIndexEnd;
            endOffset   += shardIndexEnd;
            const uint64_t minishardLength(endOffset - startOffset);
            if (m_debugFlag) std::cout << "   entry i: startOffset=" << std::hex << startOffset << ", endOffset=" << endOffset
            << std::dec << ", length=" << minishardLength << std::endl;
            if (minishardLength > 0) {
                minishardStartOffsetAndLength.push_back(std::make_pair(startOffset,
                                                                       minishardLength));
            }
        }
        
        /*
         * Read the minishards.  Must be done after reading start and
         * ending offset since reading minishard changes file read
         * position.
         */
        for (const auto& offsetAndLength : minishardStartOffsetAndLength) {
            const uint64_t startOffset(offsetAndLength.first);
            const uint64_t minishardLength(offsetAndLength.second);
            readEncodedMinishardIndex(file,
                                      shardingDataType,
                                      shardingInfo.m_dataEncoding,
                                      shardIndexEnd,
                                      shardingInfo.m_minishardIndexEncoding,
                                      startOffset,
                                      minishardLength);
        }
    }
}

/**
 * Read the encoded minishard index
 * @param file
 *    The QFile that is being read
 * @param shardingDataType
 *    The sharding data type
 * @param dataEncoding
 *    Type of encoding used to compress data
 * @param shardIndexEnd
 *    End of shard index
 * @param minishardIndexEncoding
 *    Encoding for the minishard indexing
 * @param minishardOffset
 *    The location of the minishard in the file
 * @param minishardLength
 *    Length of the minishard
 */
void
NeuroglancerAnnotationFileImporter::readEncodedMinishardIndex(QFile& file,
                                                       const ShardingDataType shardingDataType,
                                                       const AString& dataEncoding,
                                                       const uint64_t shardIndexEnd,
                                                       const AString& minishardIndexEncoding,
                                                       const uint64_t minishardOffset,
                                                       const uint64_t minishardLength)
{
    if (minishardLength <= 0) {
        return;
    }
    
    QByteArray uncompressedData;
    
    QByteArray compressedData;
    compressedData.resize(minishardLength);
    
    if (m_debugFlag) std::cout << "-------------------------------" << std::endl;
    if (m_debugFlag) std::cout << "Seeking to minishard offset: hex=" << std::hex << minishardOffset
       << ", dec=" << std::dec << minishardOffset<< std::endl;
    if (file.seek(minishardOffset)) {
        /*
         * Read the data (probably compressed)
         */
        const uint64_t numRead(file.read(compressedData.data(),
                                         minishardLength));
        if (numRead != minishardLength) {
            throw DataFileException("Failed to read "
                                    + AString::number(minishardLength)
                                    + " bytes.  Actually read"
                                    + AString::number(numRead)
                                    + " bytes from " + file.fileName());
        }
        
        /*
         * Decompress the minishard data
         */
        if ( ! decompressData(compressedData,
                              uncompressedData,
                              minishardIndexEncoding)) {
            return;
        }
        
        if (m_debugFlag) std::cout << "Length compressed=" << compressedData.length()
           << " uncompressed=" << uncompressedData.length() << std::endl;
        
        std::vector<ChunkInfo> minishardChunkInfo;
        processMinishardIndex(file,
                              shardingDataType,
                              shardIndexEnd,
                              uncompressedData,
                              dataEncoding,
                              minishardChunkInfo);
        
        readChunksFromShardFile(file,
                                shardingDataType,
                                dataEncoding,
                                minishardChunkInfo);
        
    }
    else {
        throw DataFileException("Failed to seek to "
                                + AString::number(minishardOffset)
                                + " in " + file.fileName());
    }
}

/**
 * Process a minishard
 * @param file
 *    The QFile that is being read
 * @param shardingDataType
 *    The sharding data type
 * @param shardIndexEnd
 *    End of shard index
 * @param minishardIndexData
 *    Data in the minishard index
 * @param dataEncoding
 *    Encoding of the chunk data
 * @param miniShardChunkInfoOut
 *    Output contains chunk info from the minishard index
 */
void
NeuroglancerAnnotationFileImporter::processMinishardIndex(QFile& file,
                                                   const ShardingDataType shardingDataType,
                                                   const uint64_t shardIndexEnd,
                                                   const QByteArray& minishardIndexData,
                                                   const AString& dataEncoding,
                                                   std::vector<ChunkInfo>& miniShardChunkInfoOut)
{
    /*
     * The "minishard index" stored in the shard file is encoded according to the
     * minishard_index_encoding metadata value. The decoded "minishard index" is a
     * binary string of 24*n bytes, specifying a contiguous C-order array of [3, n]
     * uint64le values. Values array[0, 0], ..., array[0, n-1] specify the chunk IDs
     * in the minishard, and are delta encoded, such that array[0, 0] is equal to the
     * ID of the first chunk, and the ID of chunk i is equal to the sum of
     * array[0, 0], ..., array[0, i]. The size of the data for chunk i is stored as
     * array[2, i]. Values array[1, 0], ..., array[1, n-1] specify the starting
     * offsets in the shard file of the data corresponding to each chunk, and are
     * also delta encoded relative to the end of the prior chunk, such that the
     * starting offset of the first chunk is equal to shard_index_end + array[1, 0],
     * and the starting offset of chunk i is the sum of
     * shard_index_end + array[1, 0], ..., array[1, i] and array[2, 0], ..., array[2, i-1].
     *
     * The start and size values in the minishard index specify the location in the
     * shard file of the chunk data, which is encoded according to the data_encoding
     * metadata value.
     */
    
    miniShardChunkInfoOut.clear();
    
    if (m_debugFlag) std::cout << "Minishard Index Data Length: " << minishardIndexData.length() << std::endl;
    
    QDataStream dataStream(minishardIndexData);
    dataStream.setByteOrder(QDataStream::LittleEndian);
    
    const int64_t numChunks(minishardIndexData.length() / 24);
    const int64_t remainder(minishardIndexData.length() % 24);
    if (remainder != 0) {
        throw DataFileException("ERROR: minishard is not evenly divisible by 24, remainder="
                                + AString::number(remainder));
        return;
    }
    
    miniShardChunkInfoOut.resize(numChunks);
    
    /*
     * Row zero (dim i=0) contains chunk IDs
     * A chunkID is relative to the previous chunk ID
     */
    uint64_t previousChunkID(0);
    for (int64_t iChunk = 0; iChunk < numChunks; iChunk++) {
        if (dataStream.atEnd()) {
            throw DataFileException("End of stream at dim i=0 iChunk="
                                    + AString::number(iChunk));
        }
        quint64 chunkID;  /* cannot use uint64_t on Linux */
        dataStream >> chunkID;
        
        chunkID += previousChunkID;
        previousChunkID = chunkID;
        

        CaretAssertVectorIndex(miniShardChunkInfoOut, iChunk);
        miniShardChunkInfoOut[iChunk].m_id = chunkID;
    }
    
    /*
     * Row one (dim i=1) contains offsets that are
     * relative to the END of the previous chunk
     */
    for (int64_t iChunk = 0; iChunk < numChunks; iChunk++) {
        if (dataStream.atEnd()) {
            throw DataFileException("End of stream at dim i=1 iChunk="
                                    + AString::number(iChunk));
        }
        quint64 chunkOffset;  /* cannot use uint64_t on Linux */
        dataStream >> chunkOffset;
        miniShardChunkInfoOut[iChunk].m_relativeOffset = chunkOffset;
    }
    
    /*
     * Row two (dim i=2) contains sizes of the chunks
     */
    for (int64_t iChunk = 0; iChunk < numChunks; iChunk++) {
        if (dataStream.atEnd()) {
            throw DataFileException("End of stream at dim i=2 iChunk="
                                    + AString::number(iChunk));
        }
        quint64 chunkSize;  /* cannot use uint64_t on Linux */
        dataStream >> chunkSize;
        
        CaretAssertVectorIndex(miniShardChunkInfoOut, iChunk);
        miniShardChunkInfoOut[iChunk].m_size = chunkSize;
    }
    
    /*
     * Now that we have sizes we can compute offsets
     * to absolute positions in the file
     */
    int64_t previousChunkEndOffset(shardIndexEnd);
    for (int64_t iChunk = 0; iChunk < numChunks; iChunk++) {
        CaretAssertVectorIndex(miniShardChunkInfoOut, iChunk);
        ChunkInfo& ci(miniShardChunkInfoOut[iChunk]);
        ci.m_offset = previousChunkEndOffset + ci.m_relativeOffset;
        
        previousChunkEndOffset = ci.m_offset + ci.m_size;
    }
    
    if (m_debugFlag) {
        for (int64_t iChunk = 0; iChunk < numChunks; iChunk++) {
            CaretAssertVectorIndex(miniShardChunkInfoOut, iChunk);
            const ChunkInfo& ci(miniShardChunkInfoOut[iChunk]);
            if (m_debugFlag) std::cout << "Chunk " << iChunk
                << ": id=" << ci.m_id << ", offset=" << ci.m_offset
                << ", rel offset=" << ci.m_relativeOffset
                << ", size=" << ci.m_size << std::endl;;
        }
    }
}

/**
 * Read data (annotations) from the chunks from the shard file
 * @param file
 *    The QFile that is being read
 * @param shardingDataType
 *    The sharding data type
 * @param dataEncoding
 *    Encoding of the chunk data
 * @param miniShardChunkInfo
 *    Info about each chunk
 */
void
NeuroglancerAnnotationFileImporter::readChunksFromShardFile(QFile& file,
                                                     const ShardingDataType shardingDataType,
                                                     const AString& dataEncoding,
                                                     const std::vector<ChunkInfo>& miniShardChunkInfo)
{
    const int64_t numChunks(miniShardChunkInfo.size());
    for (int64_t i = 0; i < numChunks; i++) {
        CaretAssertVectorIndex(miniShardChunkInfo, i);
        const ChunkInfo& chunk(miniShardChunkInfo[i]);
        
        /*
         * Seek to the location of the chunk in the file.
         */
        if (file.seek(chunk.m_offset)) {
            QByteArray compressedData(file.read(chunk.m_size));
            
            QByteArray data;
            if ( ! decompressData(compressedData,
                                  data,
                                  dataEncoding)) {
                return;
            }
            
            /*
             * The chunk contains one annotation so read it
             */
            QDataStream dataStream(data);
            
            switch (shardingDataType) {
                case ShardingDataType::ANNOTATION:
                {
                    QFile* nullFile(NULL);
                    const bool readRelationshipDataAfterAnnotationFlag(false);
                    NewAnnoationInformation nfi(readAnnotationFromDataStream(nullFile,
                                                                             data,
                                                                             dataStream,
                                                                             FeatureItemGroup::getDefaultGroupID(),
                                                                             chunk.m_id,
                                                                             readRelationshipDataAfterAnnotationFlag));

                    /*
                     * DO NOT reference nfi.m_featureAndPropertiesList
                     * after calling addFeature as it is destroyed if
                     * not added to model.
                     */
                    m_featureFile->addFeature(nfi.m_featureAndPropertiesList);
                }
                    break;
                case ShardingDataType::RELATIONSHIP:
                    readRelationshipsFromDataStream(data,
                                                    dataStream,
                                                    chunk.m_id);
                    break;
            }
        }
        else {
            throw DataFileException("Failed to seek to "
            + AString::number(chunk.m_offset)
                                    + " for chunk "
                                    + AString::number(i));
        }
    }
}

/**
 * Decompress data using the given encoding name.
 * @param compressedDataIn
 *   The input compressed data
 * @param uncompressedDataOut
 *   The output uncompressed data if successful.
 * @param encodingName
 *   Name of the compression encoding
 * @return
 *   True if sucessful, else false.
 */
bool
NeuroglancerAnnotationFileImporter::decompressData(const QByteArray& compressedDataIn,
                                            QByteArray& uncompressedDataOut,
                                            const AString encodingName)
{
    if (encodingName == "gzip") {
        /*
         * Use GZIP decompression
         */
        if ( ! DataCompressZLib::uncompressData(compressedDataIn,
                                                uncompressedDataOut)) {
            throw DataFileException(" DataCompressZLib::gzipDecompress() failed");
        }
        return true;
    }
    else if ((encodingName == "raw")
             || encodingName.isEmpty()) {
        /*
         * No compression, output is simply input
         * Note: identical QByteArrays share data until one is changed
         * so no copying of data.
         */
        uncompressedDataOut = compressedDataIn;
        return true;
    }
    else {
        throw DataFileException("Unsupported encoding compression type="
                                + encodingName);
    }
    return false;
}

/**
 * Read a relationship from a datastream
 * @param data
 *    The data
 * @param dataStream
 *    The datastream wrapped around 'data'
 * @param relationshipID
 *    The relationship ID (may be filename when each annotation in its own file)
 */
void
NeuroglancerAnnotationFileImporter::readRelationshipsFromDataStream(const QByteArray& data,
                                                                    QDataStream& dataStream,
                                                                    const uint64_t relationshipID)
{
    /*
     * Multiple annotation encoding
     * Both the related object id index and the spatial index encode lists of
     * annotations in the following binary format:
     * The number of annotations, `count`, as a uint64le value.
     * Repeated for `i = 0` up to `count - 1`:
     *
     * - The position/radii vectors, the property values, and padding bytes of
     *   the `i`th annotation are encoded exactly as in the single annotation
     *   encoding:
     *   https://github.com/google/neuroglancer/blob/master/src/datasource/precomputed/annotations.md#single-annotation-encoding
     *
     * Repeated for `i = 0` up to `count - 1`:
     *
     * - The annotation id of the `i`th annotation encoded as a uint64le value.
     *
     * For the related object id index, the order of the annotations does not
     * matter. For the spatial index, the annotations should be ordered
     * randomly.
     */

    dataStream.setByteOrder(QDataStream::LittleEndian);
    dataStream.setFloatingPointPrecision(QDataStream::SinglePrecision);
    
    uint64_t numAnn;   /* cannot use uint64_t on Linux */
    dataStream >> numAnn;
    if (m_debugFlag) {
        std::cout << "Relation ID=" << relationshipID
        << ", length=" << data.length()
        << ", num ann= " << numAnn << std::endl;
    }

    /*
     * Read the annotations
     */
    std::vector<NewAnnoationInformation> newAnnotationInfo;
    for (uint64_t i = 0; i < numAnn; i++) {
        QFile* nullFile(NULL);
        const bool readRelationshipDataAfterAnnotationFlag(false);
        uint64_t temporaryID(i); /* replaced in next loop */
        const NewAnnoationInformation nfi(readAnnotationFromDataStream(nullFile,
                                                                       data,
                                                                       dataStream,
                                                                       relationshipID,
                                                                       temporaryID,
                                                                       readRelationshipDataAfterAnnotationFlag));
        newAnnotationInfo.push_back(nfi);
    }
    
    /*
     * Now read the annotation IDs and assign IDs to annotation
     */
    for (uint64_t i = 0; i < numAnn; i++) {
        quint64 annID;  /* cannot use uint64_t on Linux */
        dataStream >> annID;
        
        CaretAssertVectorIndex(newAnnotationInfo, (int32_t)i);
        FeatureItem* featureItem(dynamic_cast<FeatureItem*>(newAnnotationInfo[i].m_featureAndPropertiesList[0]));
        CaretAssert(featureItem);
        featureItem->setUniqueID(annID);
        
        /*
         * DO NOT reference newAnnotationInfo[i].m_featureAndPropertiesList
         * after calling addFeature as it is destroyed if
         * not added to model.
         */
        m_featureFile->addFeature(newAnnotationInfo[i].m_featureAndPropertiesList);
    }
}

/**
 * Convert a neuroglancer data type to a string representation
 * @param dataType
 *    The data type
 * @return
 *    String describing data type
 */
AString
NeuroglancerAnnotationFileImporter::neuroglancerDataTypeToString(const NeuroglancerDataType& dataType)
{
    AString dataTypeName;
    switch (dataType) {
        case NeuroglancerDataType::INVALID:
            dataTypeName = "Invalid";
            break;
        case NeuroglancerDataType::RGB:
            dataTypeName = "RGB";
            break;
        case NeuroglancerDataType::RGBA:
            dataTypeName = "RGBA";
            break;
        case NeuroglancerDataType::UINT8:
            dataTypeName = "UINT8";
            break;
        case NeuroglancerDataType::INT8:
            dataTypeName = "INT8";
            break;
        case NeuroglancerDataType::UINT16:
            dataTypeName = "UINT16";
            break;
        case NeuroglancerDataType::INT16:
            dataTypeName = "INT16";
            break;
        case NeuroglancerDataType::UINT32:
            dataTypeName = "UINT32";
            break;
        case NeuroglancerDataType::INT32:
            dataTypeName = "INT32";
            break;
        case NeuroglancerDataType::FLOAT32:
            dataTypeName = "FLOAT32";
            break;
    }
    
    return dataTypeName;
}

