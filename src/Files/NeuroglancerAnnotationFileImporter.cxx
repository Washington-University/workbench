/**
 * Add file info to data file content information
 * @param dataFileInformation
 *   The data file info structure
 */
void
NeuroglancerAnnotationFileImporter::addToDataFileContentInformation(DataFileContentInformation& dataFileInformation) const
{
    dataFileInformation.addText("Starting Neuroglancer File Information...");
    dataFileInformation.addNameAndValue("Info File Directory", m_infoFileDirectoryName);
    dataFileInformation.addNameAndValue("ByID Directory", m_byIdDirectoryName);
    addShardingToDataFileInformation(dataFileInformation, "By ID Sharding", m_byIdSharding);
    dataFileInformation.addNameAndValue("Dim X", dimensionToString(m_xDimension));
    dataFileInformation.addNameAndValue("Dim Y", dimensionToString(m_yDimension));
    dataFileInformation.addNameAndValue("Dim Z", dimensionToString(m_zDimension));

    const AString annTypeName(FeatureItemTypeEnum::toGuiName(m_annotationType));
    dataFileInformation.addNameAndValue("Annotation Type", annTypeName);
    dataFileInformation.addNameAndValue("Lower Bound", AString::fromNumbers(m_lowerBound));
    dataFileInformation.addNameAndValue("Upper Bound", AString::fromNumbers(m_upperBound));

    for (const Relationship& r : m_relationships) {
        dataFileInformation.addNameAndValue("Relationships ID", r.m_id);
        dataFileInformation.addNameAndValue("Relationships Directory", r.m_directoryName);
        addShardingToDataFileInformation(dataFileInformation, "Relationships Sharding", r.m_sharding);
    }
    
    for (const NeuroglancerProperty& p : m_properties) {
        dataFileInformation.addNameAndValue("Property ID", p.m_id);
        dataFileInformation.addNameAndValue("   Description", p.m_description);
        dataFileInformation.addNameAndValue("   Property Type", neuroglancerDataTypeToString(p.m_propertyType));
        dataFileInformation.addNameAndValue("   Offset", p.m_fileOffset);
        
        if ( ! p.m_enumValueLabel.empty()) {
            for (const auto& mapInfo : p.m_enumValueLabel) {
                dataFileInformation.addNameAndValue("   ", (AString::number(mapInfo.first)
                                                            + " " + mapInfo.second));
            }
        }
    }
}

/**
 * Add description of sharding to data file information
 * @param shardingName
 *    Name of the sharding
 * @param sharding
 *    The sharding instance
 */
void
NeuroglancerAnnotationFileImporter::addShardingToDataFileInformation(DataFileContentInformation& dataFileInformation,
                                                              const AString& shardingName,
                                                              const Sharding& sharding) const
{
    dataFileInformation.addNameAndValue("Sharding Name", shardingName);
    if (sharding.m_validFlag) {
        dataFileInformation.addNameAndValue("  Sharding Type", sharding.m_type);
        dataFileInformation.addNameAndValue("  Sharding Data Encoding", sharding.m_dataEncoding);
        dataFileInformation.addNameAndValue("  Sharding Hash", sharding.m_hash);
        dataFileInformation.addNameAndValue("  Sharding Minishard Bits", sharding.m_minishardBits);
        dataFileInformation.addNameAndValue("  Sharding Minishard Index Encoding", sharding.m_minishardIndexEncoding);
        dataFileInformation.addNameAndValue("  Sharding Preshift Bits", sharding.m_preshiftBits);
        dataFileInformation.addNameAndValue("  Sharding Shard Bits", sharding.m_shardBits);
    }
}

/**
 * Read the data file.
 *
 * @param filename
 *    Name of the data file.
 * @throws DataFileException
 *    If the file was not successfully read.
 */
void
NeuroglancerAnnotationFileImporter::readFile(const AString& filename)
{
    readNeuroglancerInfoFile(filename);
    
    for (const Relationship& r : m_relationships) {
        readNeuroglancerAnnotationShardedFiles(r.m_sharding,
                                               ShardingDataType::RELATIONSHIP,
                                               r.m_directoryName);
    }
    
    if (m_byIdSharding.m_validFlag) {
        /*
         * Multiple annotations are in one or more files
         */
        readNeuroglancerAnnotationShardedFiles(m_byIdSharding,
                                               ShardingDataType::ANNOTATION,
                                               m_byIdDirectoryName);
    }
    else {
        /*
         * Each annotation is in its own file
         */
        readNeuroglancerAnnotationFiles();
    }

    /*
     * Set feature model column titles using property descriptions
     */
    if (m_featureFile->m_featureModel->columnCount() > 0) {
        QStringList headerLabels;
        headerLabels << "Point";
        for (const auto& p : m_properties) {
            headerLabels << p.m_description;
        }
        m_featureFile->m_featureModel->setHeaderLabels(headerLabels);
        
        m_featureFile->m_featureModel->updateCheckedStateOfAllItems();
    }
}

/**
 * Read the neuroglancer "info" file.  The info file (in JSON) describes the contents of the other files.
 *
 * @param filenameIn
 *    Name of the data file.
 * @throws DataFileException
 *    If the file was not successfully read or other errors.
 */
void
NeuroglancerAnnotationFileImporter::readNeuroglancerInfoFile(const AString& filenameIn)
{
   FileInformation fileInfo(filenameIn);
    const AString nameNoPath(fileInfo.getFileName());
    if (nameNoPath != "info") {
        throw DataFileException("Name of file MUST be named \"info\" but is named \""
                                + nameNoPath + "\"");
    }
    
    m_infoFileDirectoryName = fileInfo.getAbsolutePath();
    
//    const AString spatial0DirName(fileInfo.getAbsolutePath()
//                                  + QDir::separator()
//                                  + "spatial0");
    
    AString errorMessage;
        
    if ( ! errorMessage.isEmpty()) {
        throw DataFileException(errorMessage);
    }
    
    /*
     * Open the "info" file
     */
    const AString filename(fileInfo.getAbsoluteFilePath());
    QFile jsonfile(filename);
    if ( ! jsonfile.open(QIODevice::ReadOnly)) {
        throw DataFileException("Error opening "
                                + filename
                                + ": "
                                + jsonfile.errorString());
    }
    
    /*
     * Read the entire "info" file
     */
    QByteArray dataRead(jsonfile.readAll());

    /*
     * Can print to help with debugging
     */
    const bool printJsonFlag(false);
    QString s(dataRead);
    if (printJsonFlag) {
        std::cout << "-->" << s << "<---" << std::endl;
    }
    
    /*
     * Allow Qt to parse the JSON text
     */
    QJsonParseError jsonError;
    QJsonDocument json = QJsonDocument::fromJson(dataRead,
                                                 &jsonError);
    if (jsonError.error != QJsonParseError::NoError) {
        throw DataFileException("Failed to read JSON from "
                                + filename
                                + " with error: "
                                + jsonError.errorString()
                                + " at offset: "
                                + QString::number(jsonError.offset));
    }
    
    /*
     * Can print a "pretty" (formatted with indentation
     * for easier reading) version of the JSON
     */
    const bool prettyPrintFlag(true);
    if (prettyPrintFlag) {
        AString nameOut(FileInformation::assembleFileComponents(fileInfo.getAbsolutePath(),
                                                                "formatted",
                                                                "json"));
        QByteArray jsonOut(json.toJson(QJsonDocument::JsonFormat::Indented));
        QFile fileOut(nameOut);
        if (fileOut.open(QIODevice::WriteOnly)) {
            fileOut.write(jsonOut);
            fileOut.close();
        }
        else {
            throw DataFileException("Error opening " + nameOut
                                    + ": " + fileOut.errorString());
        }
    }
    
    /*
     * Top level item must be a Json Object
     */
    if ( ! json.isObject()) {
        throw DataFileException("Top level JSON in "
                                + filename
                                + " is not a JsonObject");
    }

    try {
        parseNeuroglancerInfoFileJson(fileInfo,
                                      json.object());
        
    }
    catch (const DataFileException& dfe) {
        throw DataFileException("While reading "
                                + filename
                                + ": "
                                + dfe.whatString());
    }
}

/**
 * Parse the Neuroglancer Info file JSON
 * @param topObject
 *    The top-level JSON object
 * @throw DataFileException
 */
void
NeuroglancerAnnotationFileImporter::parseNeuroglancerInfoFileJson(const FileInformation& /*fileInfo*/,
                                                          const QJsonObject& root)
{
    AString errorMessage;
    
    const AString rootTypeName = root.value("@type").toString();
    if (rootTypeName != "neuroglancer_annotations_v1") {
        errorMessage.appendWithNewLine("@type="
                                       + rootTypeName
                                       + "but should be: neuroglancer_annotations_v1");
    }
    
    const QString annTypeName(root.value("annotation_type").toString().toUpper());
    if (annTypeName == "POINT") {
        m_annotationType = FeatureItemTypeEnum::POINT;
    }
    else if (annTypeName == "LINE") {
        m_annotationType = FeatureItemTypeEnum::INVALID;
    }
    else if (annTypeName == "AXIS_ALIGNED_BOUNDING_BOX") {
        m_annotationType = FeatureItemTypeEnum::INVALID;
    }
    else if (annTypeName == "ELLIPSOID") {
        m_annotationType = FeatureItemTypeEnum::INVALID;
    }
    else if (annTypeName == "POLYLINE") {
        m_annotationType = FeatureItemTypeEnum::INVALID;
    }
    
    /*
     * We only support points
     */
    if (m_annotationType == FeatureItemTypeEnum::INVALID) {
        errorMessage.appendWithNewLine("annotation_type="
                                       + annTypeName
                                       + " not supported.");
    }
    
    if ( ! errorMessage.isEmpty()) {
        throw DataFileException(errorMessage);
    }
    
    
    parseByIdObject(root.value("by_id").toObject());

    parseDimensionsObject(root.value("dimensions").toObject());
    
    m_lowerBound = parseFloatArray(root.value("lower_bound").toArray());
    m_upperBound = parseFloatArray(root.value("upper_bound").toArray());

    parsePropertiesArray(root.value("properties").toArray());
    parseSpatialArray(root.value("spatial").toArray());
    parseRelationshipsArray(root.value("relationships").toArray());
}

/**
 * Parse a float array into a float vector
 * @param array
 *   The json array
 * @return
 *    A float vector
 */
std::vector<float>
NeuroglancerAnnotationFileImporter::parseFloatArray(const QJsonArray &array)
{
    std::vector<float> arrayOut;
    arrayOut.reserve(array.size());
    for (const QJsonValue& v : array) {
        arrayOut.push_back(v.toDouble());
    }
    return arrayOut;
}

/**
 * Parse an int array into a int vector
 * @param array
 *   The json array
 * @return
 *    A int vector
 */
std::vector<int32_t>
NeuroglancerAnnotationFileImporter::parseIntArray(const QJsonArray &array)
{
    std::vector<int32_t> arrayOut;
    arrayOut.reserve(array.size());
    for (const QJsonValue& v : array) {
        arrayOut.push_back(v.toInt());
    }
    return arrayOut;
}

/**
 * Parse a dimension object
 * @param dimsObj
 *   The dimensions object
 */
void
NeuroglancerAnnotationFileImporter::parseDimensionsObject(const QJsonObject &dimsObj)
{
    for (auto it = dimsObj.constBegin(); it != dimsObj.constEnd(); ++it) {
        const QJsonArray pair = it.value().toArray();
        const AString dimName(it.key().toLower());
        Axis axis(Axis::X);
        if (dimName == "x") {
            axis = Axis::X;
        }
        else if (dimName == "y") {
            axis = Axis::Y;
        }
        else if (dimName == "z") {
            axis = Axis::Z;
        }
        else {
            throw DataFileException("Unrecogized dimension="
                                    + it.key());
        }
        
        float resolution(0.0);
        Unit unit(Unit::UNITLESS);
        if (pair.size() >= 1) {
            resolution = pair.at(0).toDouble();
        }
        float unitScale = 1.0;
        if (pair.size() >= 2) {
            const QString unitName(pair.at(1).toString().toLower());
            if (unitName == "m") {
                unit = Unit::MILLIMETERS;
                unitScale = 1000;
            }
            else if (unitName == "cm") {
                unit = Unit::MILLIMETERS;
                unitScale = 100;
            }
            else if (unitName == "mm") {
                unit = Unit::MILLIMETERS;
                unitScale = 1.0;
            }
            else if (unitName == "um") {
                unit = Unit::MILLIMETERS;
                unitScale = 0.001;
            }
            else if (unitName == "nm") {
                unit = Unit::MILLIMETERS;
                unitScale = 0.000001;
            }
            else if (unitName == "s") {
                unit = Unit::SECONDS;
            }
            else if (unitName.isEmpty()) {
                unit = Unit::UNITLESS;
            }
            else {
                throw DataFileException("Unsupported unit="
                                        + pair.at(1).toString());
            }
            
            switch (unit) {
                case Unit::MILLIMETERS:
                    break;
                case Unit::SECONDS:
                    throw DataFileException("Seconds not supported for unit");
                    break;
                case Unit::UNITLESS:
                    throw DataFileException("Unitless not supported for unit");
                    break;
            }
        }
        
        Dimension* d(NULL);
        switch (axis) {
            case Axis::X:
                d = &m_xDimension;
                d->m_axis = Axis::X;
                break;
            case Axis::Y:
                d = &m_yDimension;
                d->m_axis = Axis::Y;
                break;
            case Axis::Z:
                d = &m_zDimension;
                d->m_axis = Axis::Z;
                break;
        }
        d->m_units      = unit;
        d->m_unitScale  = unitScale;
        d->m_resolution = resolution;
        d->m_valid      = true;
    }
}

/**
 * Parse the "by_id" object
 * @param The by_id objectr
 */
void
NeuroglancerAnnotationFileImporter::parseByIdObject(const QJsonObject& byIdObject)
{
    const AString byIdDirName(byIdObject.value("key").toString());
    if (byIdDirName.isEmpty()) {
        throw DataFileException("by_id is missing or empty.");
    }
    else {
        m_byIdDirectoryName = (m_infoFileDirectoryName
                               + QDir::separator()
                               + byIdDirName);
        if ( ! QDir(m_byIdDirectoryName).exists()) {
            throw DataFileException("by_id directory does not exist: "
                                    + m_byIdDirectoryName);
        }
    }
    
    if (byIdObject.contains("sharding")) {
        const QJsonObject shardingObject(byIdObject.value("sharding").toObject());
        m_byIdSharding = parseShardingObject(shardingObject);
    }
}

/**
 * Parse a sharding object
 * @param shardingObject
 *    The JSON sharding object
 * @return
 *    Sharding class instance
 */
NeuroglancerAnnotationFileImporter::Sharding
NeuroglancerAnnotationFileImporter::parseShardingObject(const QJsonObject shardingObject)
{
    Sharding sharding;
    sharding.m_type = shardingObject.value("@type").toString();
    sharding.m_dataEncoding = shardingObject.value("data_encoding").toString();
    sharding.m_hash = shardingObject.value("hash").toString();
    sharding.m_minishardBits = shardingObject.value("minishard_bits").toInt();
    sharding.m_minishardIndexEncoding = shardingObject.value("minishard_index_encoding").toString();
    sharding.m_preshiftBits = shardingObject.value("preshift_bits").toInt();
    sharding.m_shardBits = shardingObject.value("shard_bits").toInt();
    
    sharding.m_validFlag = false;
    if (sharding.m_type.isNotEmpty()
        && sharding.m_dataEncoding.isNotEmpty()
        && sharding.m_hash.isNotEmpty()
        && (sharding.m_minishardBits >= 0)
        && sharding.m_minishardIndexEncoding.isNotEmpty()
        && (sharding.m_preshiftBits >= 0)
        && (sharding.m_shardBits >= 0)) {
        sharding.m_validFlag = true;
    }

    return sharding;
}

/**
 * Parse a relationships object
 * @param relationshipsArray
 *   The relationships array
 */
void
NeuroglancerAnnotationFileImporter::parseRelationshipsArray(const QJsonArray& relationshipsArray)
{
    const int32_t numElem(relationshipsArray.count());
    for (int32_t i = 0; i < numElem; i++) {
        Relationship relationship;
        const QJsonObject& relationshipsObject = relationshipsArray.at(i).toObject();
        const AString dirName(relationshipsObject.value("key").toString());
        if (dirName.isNotEmpty()) {
            relationship.m_directoryName = (m_infoFileDirectoryName
                                            + QDir::separator()
                                            + dirName);
            if ( ! QDir(relationship.m_directoryName).exists()) {
                throw DataFileException("relationships directory does not exist: "
                                        + relationship.m_directoryName);
            }
        }
        
        relationship.m_id = relationshipsObject.value("id").toString();
        
        if (relationshipsObject.contains("sharding")) {
            const QJsonObject shardingObject(relationshipsObject.value("sharding").toObject());
            relationship.m_sharding = parseShardingObject(shardingObject);
        }
        m_relationships.push_back(relationship);
    }
}


/**
 * Parse a properties array
 * @param propsArray
 *    The properties array
 */
void
NeuroglancerAnnotationFileImporter::parsePropertiesArray(const QJsonArray &propsArr)
{
    /*
     * m_lowerBound.size() == 3 for XYZ
     */
    int64_t offset(sizeof(float) * m_lowerBound.size());
    switch (m_annotationType) {
        case FeatureItemTypeEnum::INVALID:
            CaretAssert(0);
            break;
        case FeatureItemTypeEnum::POINT:
            /* One XYZ */
            offset *= 1;
            break;
    }
    
    for (const QJsonValue &pv : propsArr) {
        const QJsonObject po = pv.toObject();
        
        const AString id(po.value("id").toString());
        const AString description(po.value("description").toString());
        const AString typeName(po.value("type").toString().toLower());

        NeuroglancerDataType dataType(NeuroglancerDataType::INVALID);
        int32_t dataTypeSize(0);
        if (typeName == "rgb") {
            dataType = NeuroglancerDataType::RGB;
            dataTypeSize = 3;
        }
        else if (typeName == "rgba") {
            dataType = NeuroglancerDataType::RGBA;
            dataTypeSize = 4;
        }
        else if (typeName == "uint8") {
            dataType = NeuroglancerDataType::UINT8;
            dataTypeSize = 1;
        }
        else if (typeName == "int8") {
            dataType = NeuroglancerDataType::INT8;
            dataTypeSize = 1;
        }
        else if (typeName == "uint16") {
            dataType = NeuroglancerDataType::UINT16;
            dataTypeSize = 2;
        }
        else if (typeName == "int16") {
            dataType = NeuroglancerDataType::INT16;
            dataTypeSize = 2;
        }
        else if (typeName == "uint32") {
            dataType = NeuroglancerDataType::UINT32;
            dataTypeSize = 4;
        }
        else if (typeName == "int32") {
            dataType = NeuroglancerDataType::INT32;
            dataTypeSize = 4;
        }
        else if (typeName == "float32") {
            dataType = NeuroglancerDataType::FLOAT32;
            dataTypeSize = 4;
        }
        else {
            throw DataFileException("Unknown type=" + typeName);
        }
        CaretAssert(dataType != NeuroglancerDataType::INVALID);
        
        std::vector<AString> enumLabels;
        if (po.contains("enum_labels")) {
            for (const QJsonValue &lv : po.value("enum_labels").toArray())
                enumLabels.push_back(lv.toString());
        }
        
        std::vector<int32_t> enumValues;
        if (po.contains("enum_values")) {
            enumValues = parseIntArray(po.value("enum_values").toArray());
        }
        
        NeuroglancerProperty property;
        property.m_propertyType = dataType;
        property.m_description = description;
        property.m_id = id;
        property.m_fileOffset = offset;
        property.m_labelModel = NULL;

        if ( ! enumLabels.empty()) {
            if (enumLabels.size() == enumValues.size()) {
                FeatureLabelModel* labelModel(new FeatureLabelModel(description));
                const int32_t numItems(enumLabels.size());
                for (int32_t i = 0; i < numItems; i++) {
                    property.m_enumValueLabel.insert(std::make_pair(enumValues[i],
                                                                    enumLabels[i]));
                    FeatureLabel* label(new FeatureLabel(enumValues[i],
                                                                                       enumLabels[i]));
                    labelModel->addLabel(label);
                }
                m_featureFile->m_labelModels.emplace_back(labelModel);
                property.m_labelModel = labelModel;
            }
            else {
                throw DataFileException("Number of enum values="
                                        + AString::number(enumValues.size())
                                        + " and enum labels="
                                        + AString::number(enumLabels.size())
                                        + " do not match for property: "
                                        + description);
            }
        }

        m_properties.push_back(property);

        offset += dataTypeSize;
    }
}

/**
 * Parse a spatial array
 * @param spatialArray
 *   The spatial array
 * @return
 *   The spatial grid into
 */
std::vector<NeuroglancerAnnotationFileImporter::SpatialGrid>
NeuroglancerAnnotationFileImporter::parseSpatialArray(const QJsonArray &spatialArray)
{
    std::vector<SpatialGrid> grids;
    grids.reserve(spatialArray.size());
    
    for (const QJsonValue &sv : spatialArray) {
        const QJsonObject so = sv.toObject();
        
        SpatialGrid g;
        g.m_path = so.value("key").toString();
        g.m_chunkSize = parseIntArray(so.value("chunk_size").toArray());
        g.m_gridShape = parseIntArray(so.value("grid_shape").toArray());
        g.m_limit = so.value("limit").toInt();
        
        grids.push_back(g);
    }
    return grids;
}

