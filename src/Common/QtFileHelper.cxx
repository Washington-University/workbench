/**
 * QFile::skip() was added in Qt 5.10.0.  This function was
 * generated by Google AI to add a skip() function for Qt
 * versions prior to 5.10.0.
 * Skips up to maxSize bytes from the device. Returns the number of bytes actually skipped, or -1 on error.
 * @param device
 *    Device being read from (ie QFile*)
 * @param maxSize
 *    Bytes to skip
 * @return Number of bytes skipped
 */
qint64
QtFileHelper::safeSkip(QIODevice *device, qint64 maxSize)
{
#if QT_VERSION >= QT_VERSION_CHECK(5, 10, 0)
    // Fast path for Qt 5.10+ and Qt 6
    return device->skip(maxSize);
#else
    // Fallback path for Qt 5.9 and earlier
    if (device->isSequential()) {
        // Sequential device fallback: must manually read and discard data
        qint64 bytesSkipped = 0;
        char dummy[4096];
        while (bytesSkipped < maxSize) {
            qint64 toRead = qMin(maxSize - bytesSkipped, static_cast<qint64>(sizeof(dummy)));
            qint64 readResult = device->read(dummy, toRead);
            if (readResult <= 0) break; // Error or EOF
            bytesSkipped += readResult;
        }
        return bytesSkipped;
    } else {
        // Random-access device fallback: use seek relative to current position
        qint64 currentPos = device->pos();
        qint64 newPos = qMin(currentPos + maxSize, device->size());
        if (device->seek(newPos)) {
            return newPos - currentPos;
        }
        return -1; // Seek failed
    }
#endif
}


